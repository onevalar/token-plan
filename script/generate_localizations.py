#!/usr/bin/env python3
"""Builds Localization/<lang>.lproj/Localizable.strings from script/l10n/part*.py and checks coverage.

Usage:
  script/generate_localizations.py            write the .strings files (fails if a source key lacks a translation)
  script/generate_localizations.py --report   list missing / unused keys without writing
Pass a .stringsdata directory (from `swift build -Xswiftc -emit-localized-strings ...`) as the last
argument to include compiler-extracted String(localized:) keys in the coverage check.
"""
import glob, importlib.util, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ['zh-Hans', 'zh-Hant', 'ja', 'ko']
sys.path.insert(0, os.path.join(ROOT, 'script'))
import extract_localization_keys as ex

def load():
    table = {}
    for f in sorted(glob.glob(os.path.join(ROOT, 'script', 'l10n', 'part*.py'))):
        spec = importlib.util.spec_from_file_location(os.path.basename(f)[:-3], f)
        mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
        for k, v in mod.T.items():
            assert len(v) == 4, f'{f}: {k!r} needs 4 translations'
            table[k] = v
    return table

def placeholders(s):
    return sorted(re.findall(r'%(?:\d+\$)?(?:ll)?[@dlfs]|%%', s))

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

def main():
    report = '--report' in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if args:
        sys.argv = [sys.argv[0]] + args
    needed = {k for k in ex.keys() if k not in ('', 'record_shortcut')}
    table = load()
    missing = sorted(needed - set(table))
    unused = sorted(set(table) - needed)
    bad = []
    strip = lambda text: sorted(re.sub(r'\d+\$', '', p) for p in re.findall(r'%(?:\d+\$)?(?:ll)?[@dlfs]|%%', text))
    for k, vals in table.items():
        for lang, v in zip(LANGS, vals):
            if strip(k) != strip(v):
                bad.append((lang, k))
    if report or missing or bad:
        print(f'{len(needed)} keys needed, {len(table)} translated')
        for k in missing: print('MISSING', repr(k))
        for lang, k in bad: print('PLACEHOLDER MISMATCH', lang, repr(k))
        if report:
            for k in unused: print('UNUSED', repr(k))
        if missing or bad:
            sys.exit(1 if not report else 0)
        if report:
            return
    for i, lang in enumerate(LANGS):
        d = os.path.join(ROOT, 'Localization', f'{lang}.lproj')
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, 'Localizable.strings'), 'w', encoding='utf-8') as out:
            out.write('/* Generated by script/generate_localizations.py — edit script/l10n/*.py instead. */\n')
            for k in sorted(table):
                out.write(f'"{esc(k)}" = "{esc(table[k][i])}";\n')
    d = os.path.join(ROOT, 'Localization', 'en.lproj'); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, 'Localizable.strings'), 'w', encoding='utf-8') as out:
        out.write('/* English is the source language: keys are the English text. */\n')
    print(f'wrote {len(LANGS)} languages, {len(table)} strings each')

if __name__ == '__main__':
    main()
